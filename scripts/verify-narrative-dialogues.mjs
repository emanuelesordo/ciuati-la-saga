import assert from 'node:assert/strict';
import {parseWhatsApp,sanitizeArchive,readArchive,selectDialogueWindows,storySimilarity} from '../lib/narrative-dialogues.ts';
import {readChatFile} from '../lib/chat-zip.ts';
import {deflateRawSync} from 'node:zlib';
const input='[28/03/26, 10:12:11] Mario Rosi: La pizza con nduja?\n[28/03/26, 10:13:11] Ema: Guglielmo e pizza, certo.\n[28/03/26, 10:14:11] Mario Rosi: Ema, chiamami al +39 333 123 4567\n[28/03/26, 10:15:11] Ema: <Media omessi>\n06/09/26, 18:00 - Mario Rosi: Brugge e birra\n06/09/26, 18:01 - Ema: Birreria e viaggio';
const raw=parseWhatsApp(input);
assert.equal(raw.length,5);
assert.equal(raw[0].date,'2026-03-28');
const archive=sanitizeArchive(raw,{'Mario Rosi':'Barretta','Ema':'Viper'});
assert.equal(archive.messages.length,5);
assert.ok(archive.messages[2].text.includes('Viper'));
assert.ok(!archive.messages[2].text.includes('333'));
const early=selectDialogueWindows(readArchive(archive),'Barretta Viper pizza nduja','',true);
assert.ok(early.length>0);
assert.ok(early.every(x=>x.date<'2026-06-01'));
const later=selectDialogueWindows(archive,'Brugge birra viaggio','',false);
assert.ok(later.some(x=>x.date==='2026-09-06'));
assert.equal(storySimilarity('uno due tre quattro cinque sei','uno due tre quattro cinque sei'),1);
assert.equal(storySimilarity('uno due tre quattro cinque sei','una storia diversa con altre parole'),0);
const content=Buffer.from(input),compressed=deflateRawSync(content),name=Buffer.from('_chat.txt');
const local=Buffer.alloc(30);local.writeUInt32LE(0x04034b50,0);local.writeUInt16LE(8,8);local.writeUInt32LE(compressed.length,18);local.writeUInt32LE(content.length,22);local.writeUInt16LE(name.length,26);
const central=Buffer.alloc(46);central.writeUInt32LE(0x02014b50,0);central.writeUInt16LE(8,10);central.writeUInt32LE(compressed.length,20);central.writeUInt32LE(content.length,24);central.writeUInt16LE(name.length,28);
const offset=local.length+name.length+compressed.length;
const end=Buffer.alloc(22);end.writeUInt32LE(0x06054b50,0);end.writeUInt16LE(1,8);end.writeUInt16LE(1,10);end.writeUInt32LE(central.length+name.length,12);end.writeUInt32LE(offset,16);
const zip=new File([local,name,compressed,central,name,end],'export.zip');
assert.equal(await readChatFile(zip),input);
assert.equal(await readChatFile(new File([input],'chat.txt')),input);
console.log('Dialoghi: parsing, alias, recapiti, selezione cronologica, somiglianza e ZIP verificati.');
